"""STATION 5 · PRINT — song.json → beautiful lyrics+chords PDF"""
import sys, json, html, subprocess, tempfile, os

song_f, title, artist, out_pdf = sys.argv[1:5]
song = json.load(open(song_f))

rows = []
for ln in song["lines"]:
    rows.append(
        f'<div class="line"><span class="chord">{html.escape(ln.get("chord") or "")}</span>'
        f'<div class="words">{html.escape(ln["text"])}</div></div>')

page = f"""<!DOCTYPE html><html><head><meta charset="utf-8"><style>
  @page {{ size: A4; margin: 18mm 16mm; }}
  body {{ font-family: Georgia, 'Times New Roman', serif; color:#1a1420; }}
  h1 {{ font-size: 22pt; margin: 0 0 2pt; }}
  .artist {{ color:#6b5f7a; font-size: 11pt; margin-bottom: 4pt; }}
  .meta {{ color:#a094b3; font-size: 8.5pt; margin-bottom: 16pt; }}
  .line {{ margin: 0 0 11pt; page-break-inside: avoid; }}
  .chord {{ color:#c2410c; font-weight:700; font-family: ui-monospace, monospace; font-size: 10pt; letter-spacing:.05em; }}
  .words {{ font-size: 13pt; font-weight: 600; line-height: 1.3; }}
  .foot {{ margin-top: 20pt; color:#a094b3; font-size: 8pt; border-top: 1px solid #e5ddf0; padding-top: 6pt; }}
</style></head><body>
  <h1>{html.escape(title)}</h1>
  <div class="artist">{html.escape(artist)}</div>
  <div class="meta">THE KARAOKE PROTOCOL v0.1 🔥 · lyrics + chords · ♩={song.get('bpm','?')} · draft — artist to bless</div>
  {''.join(rows)}
  <div class="foot">Generated by the AI ʻohana 🌺 · CC0 — fork me like crazy 🍴 · any track → karaoke in seconds</div>
</body></html>"""

with tempfile.NamedTemporaryFile("w", suffix=".html", delete=False) as f:
    f.write(page); tmp = f.name
chromium = None
for c in ("chromium", "chromium-browser", "google-chrome"):
    if subprocess.run(["which", c], capture_output=True).returncode == 0:
        chromium = c; break
if not chromium:
    chromium = "/ms-playwright/chromium-1223/chrome-linux64/chrome"
    import glob; chromium = ([chromium] if os.path.exists(chromium) else [])[0]
subprocess.run([chromium, "--headless", "--no-sandbox", "--disable-gpu",
                f"--print-to-pdf={out_pdf}", "--no-pdf-header-footer", tmp], check=True,
               capture_output=True)
os.unlink(tmp)
print(f"PRINT ✓ PDF → {out_pdf}")
